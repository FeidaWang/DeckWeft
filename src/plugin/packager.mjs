import path from 'node:path';
import { cp,mkdir,readdir,readFile,writeFile,lstat,rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { zipFiles } from '../render/zip.mjs';
import { VERSION } from '../core/model.mjs';
export const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
export const RUNTIME_PATHS=['package.json','plugin.json','.codex-plugin/plugin.json','.claude-plugin/plugin.json','bin','src','schemas','roadmap.json','AGENTS.md','public','examples','skills','integrations','LICENSE','NOTICE.md'];
export async function copyRuntime(destination){
  await mkdir(destination,{recursive:true});
  for(const name of RUNTIME_PATHS){await mkdir(path.dirname(path.join(destination,name)),{recursive:true});await cp(path.join(ROOT,name),path.join(destination,name),{recursive:true,errorOnExist:true,force:false});}
  const runtimePackage=JSON.parse(await readFile(path.join(destination,'package.json'),'utf8'));
  delete runtimePackage.devDependencies;runtimePackage.scripts={start:'node bin/deckweft.mjs studio --open',doctor:'node bin/deckweft.mjs doctor'};
  await writeFile(path.join(destination,'package.json'),JSON.stringify(runtimePackage,null,2)+'\n');
  // Runtime packages do not include the full source documentation tree.
  for(const adapter of ['figma','after-effects']){
    const guide=path.join(destination,'integrations',adapter,'README.md');
    await writeFile(guide,(await readFile(guide,'utf8')).replace(' · [Installation](../../docs/en/installation.md)',''));
  }
}
export async function filesIn(directory,prefix=''){
  const entries=[];
  for(const name of (await readdir(directory)).sort()){
    const file=path.join(directory,name),relative=prefix?`${prefix}/${name}`:name,s=await lstat(file);
    if(s.isSymbolicLink())throw new Error('Do not package symlinks.');
    if(s.isDirectory())entries.push(...await filesIn(file,relative));else entries.push([relative,await readFile(file)]);
  }
  return entries;
}
export async function buildPlugin(output=path.join(ROOT,'dist')){
  const destination=path.join(path.resolve(output),'deckweft-plugin');
  // Only this generated directory is replaced. Arbitrary output children are not removed.
  const marker=path.join(destination,'.deckweft-build');
  let present=false;
  try{await lstat(destination);present=true;}catch(e){if(e.code!=='ENOENT')throw e;}
  if(present){
    let owned=false;try{owned=(await readFile(marker,'utf8'))==='generated by deckweft\n';}catch{}
    if(!owned)throw Error('Output is not a DeckWeft build. Move it aside instead of overwriting it.');
    await rm(destination,{recursive:true});
  }
  await mkdir(destination,{recursive:true});await writeFile(marker,'generated by deckweft\n');
  await copyRuntime(path.join(destination,'runtime'));
  for(const name of ['plugin.json','.codex-plugin','.claude-plugin','skills','LICENSE','NOTICE.md']){
    if(name==='.claude-plugin'){
      await mkdir(path.join(destination,name),{recursive:true});
      await cp(path.join(ROOT,name,'plugin.json'),path.join(destination,name,'plugin.json'));
    }else await cp(path.join(ROOT,name),path.join(destination,name),{recursive:true});
  }
  await writeFile(path.join(destination,'README.md'),`# DeckWeft native plugin

This is the generated plugin package, not the source repository. It includes native host manifests, skills, a complete CLI/studio runtime, and experimental design-app importers. No API key or dependency download is required by the runtime. Node.js 22+ is required.

From this folder, run the local studio with:

\`\`\`bash
node runtime/bin/deckweft.mjs studio --open
\`\`\`

Load this folder using the host's native plugin interface. In Claude Code, start a session with \`claude --plugin-dir /absolute/path/to/this/folder\`, then invoke \`/deckweft:deck\`. Codex activation depends on the supported host surface; registration alone is not an activation test. The source distribution includes the local-marketplace catalogs.

To copy standalone skills instead, run \`node runtime/bin/deckweft.mjs install --target both --scope user --dry-run\`, inspect the plan, then repeat without \`--dry-run\`. Do not install both routes unnecessarily.

The actual Figma/AE importer source is under \`runtime/integrations/\`. It is experimental, not a hosted design connection. Real host discovery and design-app execution remain acceptance checks.

Preserve LICENSE and NOTICE.md. English is primary; the studio and Chinese example also support Simplified Chinese. 中文：此目录是原生插件包，运行文件位于 runtime；宿主实际加载仍需验收，导入器不等于已渲染视频。
`);
  const archive=path.join(path.resolve(output),`deckweft-plugin-${VERSION}.zip`);
  await writeFile(archive,zipFiles(await filesIn(destination)));
  return {directory:destination,archive,version:VERSION};
}
